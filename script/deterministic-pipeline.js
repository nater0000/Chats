import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { remark } from 'remark';
import { visit } from 'unist-util-visit';
import OpenAI from 'openai';
import ffmpeg from 'fluent-ffmpeg';
import ffmpegInstaller from '@ffmpeg-installer/ffmpeg';
import ffprobeInstaller from '@ffprobe-installer/ffprobe';
import * as mm from 'music-metadata';
import { Octokit } from '@octokit/rest';

ffmpeg.setFfmpegPath(ffmpegInstaller.path);
ffmpeg.setFfprobePath(ffprobeInstaller.path);

const kokoro = new OpenAI({ baseURL: 'https://voice.i.rickey.io/v1', apiKey: 'local' });
const octokit = new Octokit({ auth: process.env.GITHUB_TOKEN });
const [owner, repo] = (process.env.GITHUB_REPOSITORY || 'local/fallback').split('/');
const RELEASE_TAG = 'audio-assets';

const PAGES_DIR = './pages';
const TMP_DIR = './tmp_audio';

if (!fs.existsSync(TMP_DIR)) fs.mkdirSync(TMP_DIR);

function getAssetInfo(filePath) {
    const relPath = path.relative('.', filePath);
    const pathHash = crypto.createHash('md5').update(relPath).digest('hex').substring(0, 8);
    const cleanPath = relPath
        .replace(/\.md$/i, '')
        .replace(/[^a-zA-Z0-9]/g, '-')
        .replace(/-+/g, '-')
        .replace(/^-|-$/g, '')
        .toLowerCase();
    
    const assetName = `${cleanPath}-${pathHash}.mp3`;
    const downloadUrl = `https://github.com/${owner}/${repo}/releases/download/${RELEASE_TAG}/${assetName}`;
    return { relPath, pathHash, assetName, downloadUrl };
}

async function getOrCreateRelease() {
    try {
        const response = await octokit.rest.repos.getReleaseByTag({ owner, repo, tag: RELEASE_TAG });
        return response.data;
    } catch (e) {
        const response = await octokit.rest.repos.createRelease({ 
            owner, repo, tag_name: RELEASE_TAG, name: 'Blog Audio Assets', 
            body: 'Automated TTS audio files generated by Kokoro.'
        });
        return response.data;
    }
}

function getSortedFiles() {
    function walkDir(dir) {
        let results = [];
        const list = fs.readdirSync(dir);
        list.forEach(file => {
            const fullPath = path.join(dir, file);
            if (fs.statSync(fullPath).isDirectory()) {
                results = results.concat(walkDir(fullPath));
            } else if (fullPath.endsWith('.md')) {
                results.push(fullPath);
            }
        });
        return results;
    }

    const files = walkDir(PAGES_DIR);
    return files.map(filePath => {
        const stats = fs.statSync(filePath);
        return { filePath, mtime: stats.mtimeMs };
    }).sort((a, b) => b.mtime - a.mtime);
}

function generateSilence(durationMs, outputPath) {
    return new Promise((resolve, reject) => {
        ffmpeg().input('anullsrc=r=24000:cl=mono').inputFormat('lavfi')
            .duration(durationMs / 1000).audioCodec('libmp3lame')
            .save(outputPath).on('end', resolve).on('error', reject);
    });
}

async function processFile(fileObj, release) {
    const { relPath, pathHash, assetName, downloadUrl } = getAssetInfo(fileObj.filePath);
    const finalAudioPath = path.join(TMP_DIR, assetName);

    console.log(`\nProcessing ${relPath} (Asset: ${assetName})...`);
    const mdRaw = fs.readFileSync(fileObj.filePath, 'utf8');
    
    if (mdRaw.includes('\naudio: ')) {
        console.log(`Skipping ${relPath}: Audio tag already exists.`);
        return;
    }

    const match = mdRaw.match(/^(---[\s\S]*?---\r?\n)([\s\S]*)$/);
    if (!match) return;
    
    const frontmatter = match[1];
    const body = match[2];

    const chunks = [];
    const processor = remark();
    const ast = processor.parse(body);

    visit(ast, (node) => {
        if (node.type === 'paragraph' || node.type === 'heading') {
            let text = '';
            visit(node, ['text', 'inlineCode'], n => { text += n.value + ' '; });
            text = text.replace(/\s+/g, ' ').trim();
            
            if (text && !text.startsWith('<')) {
                chunks.push({ 
                    kokoro_prompt: text, 
                    speed: 1.15, 
                    trailing_silence_ms: 350, 
                    nodeRef: node 
                });
            }
        }
    });

    console.log(`Locally parsed ${chunks.length} blocks for TTS.`);

    const command = ffmpeg();
    let currentTime = 0;
    const tempFiles = [];

    for (let i = 0; i < chunks.length; i++) {
        const chunk = chunks[i];
        
        if (!chunk.kokoro_prompt.replace(/[^a-zA-Z0-9]/g, '').trim()) {
            console.log(`Skipping chunk ${i} (Unpronounceable): "${chunk.kokoro_prompt}"`);
            chunk.start_time = currentTime.toFixed(3);
            chunk.end_time = currentTime.toFixed(3);
            continue;
        }

        try {
            const audioRes = await kokoro.audio.speech.create({
                model: 'kokoro', voice: 'af_bella', input: chunk.kokoro_prompt, speed: chunk.speed, response_format: 'mp3'
            });
            
            const buffer = Buffer.from(await audioRes.arrayBuffer());
            
            if (buffer.length === 0) {
                console.warn(`Warning: Kokoro returned 0 bytes for chunk ${i}`);
                chunk.start_time = currentTime.toFixed(3);
                chunk.end_time = currentTime.toFixed(3);
                continue;
            }

            const chunkPath = path.join(TMP_DIR, `temp_${pathHash}_${i}.mp3`);
            fs.writeFileSync(chunkPath, buffer);
            tempFiles.push(chunkPath);
            
            const metadata = await mm.parseFile(chunkPath);
            chunk.start_time = currentTime.toFixed(3);
            currentTime += metadata.format.duration;
            chunk.end_time = currentTime.toFixed(3);
            
            command.input(chunkPath);

            if (chunk.trailing_silence_ms > 0) {
                const silencePath = path.join(TMP_DIR, `temp_${pathHash}_silence_${i}.mp3`);
                await generateSilence(chunk.trailing_silence_ms, silencePath);
                tempFiles.push(silencePath);
                command.input(silencePath);
                currentTime += (chunk.trailing_silence_ms / 1000);
            }
        } catch (audioErr) {
            console.error(`Kokoro generation failed on chunk ${i}:`, audioErr.message);
            return;
        }
    }

    if (tempFiles.length === 0) {
        console.log(`Skipping ${relPath}: No valid audio generated.`);
        return;
    }

    await new Promise((resolve, reject) => {
        command.on('end', async () => {
            console.log(`Uploading ${assetName} to GitHub Releases...`);
            
            const allAssets = await octokit.paginate(octokit.rest.repos.listReleaseAssets, {
                owner,
                repo,
                release_id: release.id
            });

            const existingAsset = allAssets.find(a => a.name === assetName);
            if (existingAsset) {
                await octokit.rest.repos.deleteReleaseAsset({ owner, repo, asset_id: existingAsset.id });
            }

            const fileData = fs.readFileSync(finalAudioPath);
            await octokit.rest.repos.uploadReleaseAsset({
                owner, repo, release_id: release.id, name: assetName, data: fileData,
                headers: { 'content-type': 'audio/mpeg', 'content-length': fileData.length }
            });

            let modifiedBody = body;
            const validChunks = chunks.filter(c => c.start_time !== undefined && c.nodeRef.position);
            
            validChunks.sort((a, b) => b.nodeRef.position.start.offset - a.nodeRef.position.start.offset);

            for (const chunk of validChunks) {
                const startIdx = chunk.nodeRef.position.start.offset;
                const endIdx = chunk.nodeRef.position.end.offset;
                
                const before = modifiedBody.slice(0, startIdx);
                const content = modifiedBody.slice(startIdx, endIdx);
                const after = modifiedBody.slice(endIdx);
                
                const spanOpen = `<span class="sync-text" data-start="${chunk.start_time}" data-end="${chunk.end_time}">`;
                const spanClose = `</span>`;
                
                modifiedBody = before + spanOpen + content + spanClose + after;
            }

            const updatedFrontmatter = frontmatter.replace(/^---\r?\n/, `---\naudio: ${downloadUrl}\n`);
            fs.writeFileSync(fileObj.filePath, updatedFrontmatter + modifiedBody); 
            
            tempFiles.forEach(f => fs.unlinkSync(f));
            if (fs.existsSync(finalAudioPath)) fs.unlinkSync(finalAudioPath);
            
            console.log(`Successfully completed ${relPath}.`);
            resolve();
        }).on('error', reject).mergeToFile(finalAudioPath, TMP_DIR);
    });
}

async function run() {
    if (!process.env.GITHUB_TOKEN) return;
    
    const TTS_BATCH_SIZE = parseInt(process.env.TTS_BATCH_SIZE || '1', 10);
    const release = await getOrCreateRelease();
    const allFiles = getSortedFiles();

    // --- SMART GARBAGE COLLECTION ---
    console.log('\nRunning Smart Garbage Collection...');
    const validAssetNames = new Set(allFiles.map(f => getAssetInfo(f.filePath).assetName));
    
    // Protect legacy files that are currently linked in markdown frontmatter
    allFiles.forEach(f => {
        const mdRaw = fs.readFileSync(f.filePath, 'utf8');
        const audioMatch = mdRaw.match(/^audio:\s*.*?\/([^/]+?\.mp3)\s*$/m);
        if (audioMatch) {
            validAssetNames.add(audioMatch[1]);
        }
    });
    
    const allAssets = await octokit.paginate(octokit.rest.repos.listReleaseAssets, {
        owner,
        repo,
        release_id: release.id
    });

    const orphans = allAssets.filter(asset => !validAssetNames.has(asset.name));

    if (orphans.length === 0) {
        console.log('No orphaned assets found. Safe to proceed.');
    } else {
        console.log(`Found ${orphans.length} orphaned asset(s). Cleaning up...`);
        for (const orphan of orphans) {
            console.log(` Deleting ${orphan.name}...`);
            await octokit.rest.repos.deleteReleaseAsset({ owner, repo, asset_id: orphan.id });
        }
        console.log('Garbage Collection complete.');
    }
    // --------------------------------

    const pendingFiles = allFiles.filter(f => !fs.readFileSync(f.filePath, 'utf8').includes('\naudio: '));
    const filesToProcess = pendingFiles.slice(0, TTS_BATCH_SIZE);
    
    console.log(`\nFound ${pendingFiles.length} pending posts. Processing ${filesToProcess.length} this run.`);
    
    for (const fileObj of filesToProcess) {
        await processFile(fileObj, release);
    }
}

run();
